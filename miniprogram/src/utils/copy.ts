type Texts<T> = T extends (...args: never[]) => unknown
  ? never
  : T extends readonly unknown[]
    ? T
    : T extends object
      ? { [K in keyof T as T[K] extends (...args: never[]) => unknown ? never : K]: Texts<T[K]> }
      : T

/** 去掉文案表里的函数，只留纯文字，供 setData 给 WXML 用（WXML 不能调用函数）。 */
export function texts<T extends object>(o: T): Texts<T> {
  return JSON.parse(JSON.stringify(o)) as Texts<T>
}
